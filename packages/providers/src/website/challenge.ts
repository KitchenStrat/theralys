/**
 * Reconnaître qu'un site refuse la lecture automatique : page de défi
 * anti-robots (« Vérification en cours… »), pare-feu applicatif, limitation
 * de débit. Module pur.
 *
 * Quand un site répond ainsi, la lecture s'arrête et le praticien se voit
 * proposer de coller son texte. On ne réessaie pas sous une autre identité,
 * on ne résout aucun défi, on ne contourne rien : le propriétaire du site (ou
 * son hébergeur) a dit non aux robots, et notre lecteur en est un.
 */

/** Statuts par lesquels un serveur refuse l'accès à un robot (authentification, interdiction, paiement, limitation de débit…). */
const REFUSAL_STATUSES = new Set([401, 402, 403, 406, 407, 429, 451]);

/** En-têtes posés par les protections anti-robots quand elles interviennent. */
const CHALLENGE_HEADERS: readonly { name: string; value?: RegExp }[] = [
  { name: "cf-mitigated" },
  { name: "x-amzn-waf-action", value: /challenge|captcha/i },
  { name: "x-sucuri-block" },
  { name: "x-datadome", value: /protected|block|captcha/i },
  { name: "x-px-block" },
];

/** Marqueurs propres aux pages de défi (jamais présents sur une page ordinaire d'un site protégé). */
const CHALLENGE_MARKERS: readonly RegExp[] = [
  /_cf_chl_opt|cf_chl_|cf-browser-verification|cf-im-under-attack|id=["']challenge-(?:error-text|form|running)/i, // Cloudflare
  /attention required!\s*\|\s*cloudflare/i,
  /sucuri_cloudproxy_js|sucuri website firewall/i,
  /_incapsula_resource|incapsula incident id/i, // Imperva
  /captcha-delivery\.com|datadome/i,
  /px-captcha|perimeterx/i,
  /awswaf\.com\/[^"'\s]{0,200}(?:challenge|captcha)\.js|aws-waf-token/i,
  /ddos-guard|ddg-captcha/i,
  /imunify360[^<]{0,80}(?:captcha|bot-protection)|bot-protection[^<]{0,80}imunify360/i,
  /generated by wordfence|your access to this site has been limited by the site owner/i,
  /anubis_challenge|within\.website\/x\/cmd\/anubis/i,
];

/** Titres de pages d'attente ou de refus servies aux robots, en français et en anglais. */
const CHALLENGE_TITLE =
  /^\s*(?:just a moment|un instant|one moment|please wait|veuillez patienter|attention required|access denied|acc[eè]s refus[eé]|acc[eè]s interdit|security check|v[eé]rification de s[eé]curit[eé]|v[eé]rification en cours|checking your browser|robot check|are you (?:a )?(?:human|robot)|human verification|bot verification|ddos protection|pardon our interruption|403 forbidden|captcha)(?![a-z0-9À-ɏ])/i;

/** Au-delà de cette longueur de texte, une page servie en 200 est tenue pour une vraie page, quels que soient ses marqueurs. */
const INTERSTITIAL_TEXT_MAX = 600;

export type ResponseView = {
  status: number;
  header: (name: string) => string | null;
  /** Début du corps décodé (HTML) */
  body: string;
};

function hasChallengeHeader(header: ResponseView["header"]): boolean {
  return CHALLENGE_HEADERS.some(({ name, value }) => {
    const found = header(name);
    return found !== null && (value ? value.test(found) : true);
  });
}

function hasChallengeMarkup(body: string): boolean {
  const start = body.slice(0, 64 * 1024);
  const title = /<title[^>]*>([^<]{0,200})/i.exec(start)?.[1] ?? "";
  return CHALLENGE_TITLE.test(title) || CHALLENGE_MARKERS.some((marker) => marker.test(start));
}

/** Texte hors balises, scripts et styles, grossièrement : sert seulement à juger si la page est presque vide. */
function roughTextLength(body: string): number {
  return body
    .slice(0, 256 * 1024)
    .replace(/<(script|style|noscript|template)\b[\s\S]*?<\/\1>/gi, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/\s+/g, " ")
    .trim().length;
}

/**
 * La réponse est-elle un défi anti-robots ?
 * - un en-tête de protection anti-robots, quel que soit le statut ;
 * - une erreur accompagnée des marqueurs d'une page de défi (503 d'attente) ;
 * - une page servie en 200 mais presque vide et marquée comme page de défi.
 */
export function isChallengeResponse(response: ResponseView): boolean {
  if (hasChallengeHeader(response.header)) return true;
  if (response.status >= 400) return hasChallengeMarkup(response.body);
  if (response.status >= 200 && response.status < 300) return hasChallengeMarkup(response.body) && roughTextLength(response.body) <= INTERSTITIAL_TEXT_MAX;
  return false;
}

/** Le statut est-il un refus d'accès (401, 403, 429…) ? Une erreur ordinaire (404, 500, 503 de maintenance) n'en est pas un. */
export function isRefusalStatus(status: number): boolean {
  return REFUSAL_STATUSES.has(status);
}

/** La réponse est-elle un refus de lecture automatique : défi anti-robots ou statut de refus ? */
export function isAutomationRefusal(response: ResponseView): boolean {
  return isChallengeResponse(response) || isRefusalStatus(response.status);
}
