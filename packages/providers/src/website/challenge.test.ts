import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { isAutomationRefusal, isChallengeResponse, isRefusalStatus } from "./challenge";
import { cpuNow } from "./test-timing";

const fixture = (name: string): string => readFileSync(new URL(`./fixtures/${name}`, import.meta.url), "utf8");
const response = (status: number, body = "", headers: Record<string, string> = {}) => ({ status, body, header: (name: string): string | null => headers[name.toLowerCase()] ?? null });
const ORDINARY = `<html><head><title>Sophrologue à Nantes</title></head><body><h1>Bienvenue</h1><p>${"La sophrologie aide à retrouver le calme. ".repeat(30)}</p></body></html>`;

describe("refus de lecture automatique", () => {
  it("statuts de refus : authentification, interdiction, limitation de débit, raisons légales", () => {
    for (const status of [401, 402, 403, 406, 407, 429, 451]) {
      expect(isRefusalStatus(status), String(status)).toBe(true);
      expect(isAutomationRefusal(response(status, "<h1>Forbidden</h1>")), String(status)).toBe(true);
    }
    for (const status of [200, 204, 301, 400, 404, 410, 500, 502, 503]) expect(isRefusalStatus(status), String(status)).toBe(false);
  });

  it("une erreur ordinaire n'est pas un refus : page introuvable, panne, maintenance", () => {
    expect(isAutomationRefusal(response(404, "<title>Page introuvable</title><p>Cette page n'existe pas.</p>"))).toBe(false);
    expect(isAutomationRefusal(response(500, "<h1>Internal Server Error</h1>"))).toBe(false);
    expect(isAutomationRefusal(response(503, "<title>Site en maintenance</title><p>Nous revenons très vite.</p>", { "retry-after": "600" }))).toBe(false);
    expect(isAutomationRefusal(response(200, ORDINARY))).toBe(false);
  });

  it("en-tête d'une protection anti-robots : refus, quel que soit le statut", () => {
    expect(isChallengeResponse(response(403, "", { "cf-mitigated": "challenge" }))).toBe(true);
    expect(isChallengeResponse(response(200, ORDINARY, { "cf-mitigated": "challenge" }))).toBe(true);
    expect(isChallengeResponse(response(405, "", { "x-amzn-waf-action": "captcha" }))).toBe(true);
    expect(isChallengeResponse(response(202, "", { "x-amzn-waf-action": "challenge" }))).toBe(true);
    expect(isChallengeResponse(response(403, "", { "x-sucuri-block": "1" }))).toBe(true);
    expect(isChallengeResponse(response(200, ORDINARY, { "x-amzn-waf-action": "allow", server: "cloudflare" }))).toBe(false);
  });

  it("page de défi servie en erreur (503 d'attente, 403) : reconnue à son titre ou à ses marqueurs", () => {
    const interstitial = fixture("challenge.html");
    expect(isChallengeResponse(response(503, interstitial))).toBe(true);
    expect(isChallengeResponse(response(403, interstitial))).toBe(true);
    const bodies = [
      "<html><head><title>Un instant…</title></head><body>Vérification de votre navigateur</body></html>",
      "<title>Attention Required! | Cloudflare</title>",
      "<title>Access denied</title><p>Vous n'avez pas accès à ce site.</p>",
      "<title>Accès refusé</title>",
      '<html><body><script>var s={},u="/_Incapsula_Resource?SWJIYLWA=719d34d31c8e3a6e";</script></body></html>',
      '<html><script src="https://geo.captcha-delivery.com/captcha/?initialCid=x"></script></html>',
      "<html><body><!-- Sucuri WebSite Firewall - Access Denied --></body></html>",
      "<p>Your access to this site has been limited by the site owner</p><p>Generated by Wordfence</p>",
    ];
    for (const body of bodies) expect(isChallengeResponse(response(503, body)), body.slice(0, 50)).toBe(true);
  });

  it("page de défi servie en 200 : reconnue si elle est presque vide", () => {
    expect(isChallengeResponse(response(200, fixture("challenge.html")))).toBe(true);
    expect(isAutomationRefusal(response(200, fixture("challenge.html")))).toBe(true);
    expect(isChallengeResponse(response(200, "<html><head><title>Just a moment...</title></head><body><noscript>Enable JavaScript and cookies to continue</noscript></body></html>"))).toBe(true);
  });

  it("une vraie page n'est jamais prise pour un défi : scripts de protection sur un site ouvert, titre ou mots ressemblants", () => {
    // Détection de robots chargée sur les pages ordinaires d'un site protégé
    const protectedSite = ORDINARY.replace("</body>", '<script src="/cdn-cgi/challenge-platform/scripts/jsd/main.js"></script><script src="https://js.datadome.co/tags.js"></script></body>');
    expect(isChallengeResponse(response(200, protectedSite))).toBe(false);
    // Formulaire de contact protégé par un captcha
    expect(isChallengeResponse(response(200, ORDINARY.replace("</body>", '<div class="g-recaptcha" data-sitekey="x"></div><div class="cf-turnstile"></div></body>')))).toBe(false);
    // Longue page dont le titre commence comme une page d'attente
    expect(isChallengeResponse(response(200, ORDINARY.replace("Sophrologue à Nantes", "Un instant pour soi : sophrologie à Nantes")))).toBe(false);
    // Article qui parle de ces protections
    expect(isChallengeResponse(response(200, ORDINARY.replace("<h1>", "<p>Notre hébergeur utilise Wordfence et Sucuri.</p><h1>")))).toBe(false);
  });

  it("seul le début du document est examiné", () => {
    const late = `${"<p>texte</p>".repeat(20_000)}<script>window._cf_chl_opt={}</script>`;
    expect(isChallengeResponse(response(503, late))).toBe(false);
  });

  it("page presque vide : scripts, styles et blocs noscript ne comptent pas comme du texte, refermés ou non", () => {
    const marker = "<script>window._cf_chl_opt={}</script>";
    const code = "var a = 1; ".repeat(200);
    expect(isChallengeResponse(response(200, `<html><body>${marker}<script>${code}</script><style>${code}</style><p>Vérification…</p></body></html>`))).toBe(true);
    expect(isChallengeResponse(response(200, `<html><body>${marker}<p>Vérification…</p><SCRIPT type="module">${code}`))).toBe(true);
    // Le même marqueur sur une page qui a du texte : une vraie page
    expect(isChallengeResponse(response(200, `<html><body>${marker}<p>${"Un vrai paragraphe de contenu. ".repeat(40)}</p></body></html>`))).toBe(false);
  });

  it("une page d'attente est petite : une grosse page n'en est pas une, même avec un marqueur et peu de texte", () => {
    const heavy = `<html><head><script>window._cf_chl_opt={};${"var a = 1; ".repeat(40_000)}</script></head><body><p>Bonjour</p></body></html>`;
    expect(heavy.length).toBeGreaterThan(256 * 1024);
    expect(isChallengeResponse(response(200, heavy))).toBe(false);
    // En erreur, le marqueur suffit, quelle que soit la taille
    expect(isChallengeResponse(response(503, heavy))).toBe(true);
  });

  it("page fabriquée pour faire traîner l'examen : jugée en un passage", () => {
    const bodies = [`<title>x</title>${"<script ".repeat(30_000)}`, "<title ".repeat(30_000), `<title>Just a moment</title>${"<style>".repeat(30_000)}`, `_cf_chl_opt ${"<".repeat(200_000)}`, `_cf_chl_opt ${"<noscript>a</noscrip ".repeat(10_000)}`];
    for (const body of bodies) {
      const start = cpuNow();
      isChallengeResponse(response(200, body));
      isChallengeResponse(response(503, body));
      expect(cpuNow() - start, body.slice(0, 30)).toBeLessThan(1_000);
    }
  });
});
